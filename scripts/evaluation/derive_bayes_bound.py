import pandas as pd
import numpy as np
from sklearn.metrics import precision_recall_curve, auc, average_precision_score, roc_auc_score

# 1. Load data
history = pd.read_csv("data/processed/asset_history_simulated.csv", parse_dates=["snapshot_date"])
failures = pd.read_csv("data/processed/failures_simulated.csv", parse_dates=["failure_date"])
cand_ml = pd.read_csv("data/processed/candidate_v3/failure_ml_dataset.csv", parse_dates=["snapshot_date"])

# Reconstruct exact failure_score and p* as computed in 05_generate_historical_data.ipynb
# Cell 14:
# failure_score = 0.04*age + 0.06*(100-cond) + 1.5*usage + 1.2*weather + 0.5*(crit/10)
# Cell 15:
# failure_probability = 1 / (1 + exp(-(failure_score - 6)))
# Cell 17:
# failure_mask = random < failure_probability * 0.08

age = history["asset_age_years"]
cond = history["condition_score"]
usage = history["usage_factor"]
weather = history["weather_stress"]
crit = history["criticality"]

failure_score = 0.04 * age + 0.06 * (100.0 - cond) + 1.5 * usage + 1.2 * weather + 0.5 * (crit / 10.0)
p_logistic = 1.0 / (1.0 + np.exp(-(failure_score - 6.0)))
p_star = p_logistic * 0.08  # The true Bernoulli parameter

history["failure_score"] = failure_score
history["p_star"] = p_star

print("=== 1. DISTRIBUTION OF TRUE LATENT PROBABILITY p* ===")
print("p* min:   ", p_star.min())
print("p* mean:  ", p_star.mean())
print("p* median:", p_star.median())
print("p* 90th:  ", p_star.quantile(0.90))
print("p* 95th:  ", p_star.quantile(0.95))
print("p* 99th:  ", p_star.quantile(0.99))
print("p* max:   ", p_star.max())

# Now connect each snapshot to its target label in candidate_v3 (corrected target)
# cand_ml has snapshot_date from 2019-01-01 to 2026-07-01
cand_with_p = cand_ml.merge(
    history[["asset_id", "snapshot_date", "p_star", "weather_stress"]],
    on=["asset_id", "snapshot_date"],
    how="left"
)

# Note: In the simulation, when an asset experienced a failure at snapshot date T_{m+1},
# that failure was generated by Bernoulli(p*(T_{m+1})).
# What probability predicted it at T_m?
# At T_m, the asset has p*(T_m).
# What about p*(T_{m+1})?
# Let's also look up the future p*(T_{m+1})!
history_future = history[["asset_id", "snapshot_date", "p_star"]].copy()
history_future["prev_snapshot"] = history_future["snapshot_date"] - pd.DateOffset(months=1)
cand_with_p = cand_with_p.merge(
    history_future[["asset_id", "prev_snapshot", "p_star"]].rename(columns={"p_star": "p_star_next_month"}),
    left_on=["asset_id", "snapshot_date"],
    right_on=["asset_id", "prev_snapshot"],
    how="left"
)

print("\n=== 2. THEORETICAL EVALUATION OF ORACLE PREDICTIONS ===")
for split_name, mask in [
    ("Full Dataset", np.ones(len(cand_with_p), dtype=bool)),
    ("Train (2019-2024)", cand_with_p["snapshot_date"] < "2025-01-01"),
    ("Validation (2025)", (cand_with_p["snapshot_date"] >= "2025-01-01") & (cand_with_p["snapshot_date"] < "2026-01-01")),
    ("Test (Jan-Jul 2026)", cand_with_p["snapshot_date"] >= "2026-01-01")
]:
    sub = cand_with_p[mask]
    y = sub["failure_within_30_days"].values

    # Predictor 1: p*(T_m) - the true generator probability available at prediction time
    p1 = sub["p_star"].values
    prauc1 = average_precision_score(y, p1)
    rocauc1 = roc_auc_score(y, p1)

    # Predictor 2: p*(T_{m+1}) - the CHEATING future oracle that knows next month's weather & condition!
    # Fill any na with p1
    p2 = sub["p_star_next_month"].fillna(sub["p_star"]).values
    prauc2 = average_precision_score(y, p2)
    rocauc2 = roc_auc_score(y, p2)

    # Top 1% and 5% recall for p1
    n = len(y)
    k1 = int(n * 0.01)
    top1_rec = y[np.argsort(p1)[-k1:]].sum() / max(1, y.sum())
    top1_prec = y[np.argsort(p1)[-k1:]].mean()
    k5 = int(n * 0.05)
    top5_rec = y[np.argsort(p1)[-k5:]].sum() / max(1, y.sum())
    top5_prec = y[np.argsort(p1)[-k5:]].mean()

    print(f"\n--- {split_name} (Total: {n}, Positives: {y.sum()} = {y.mean()*100:.3f}%) ---")
    print(f"Predictor 1 (p* at current observation T_m):")
    print(f"  PR-AUC:  {prauc1:.5f} | ROC-AUC: {rocauc1:.5f}")
    print(f"  Top 1%:  Recall={top1_rec*100:.1f}%, Precision={top1_prec*100:.2f}%, Lift={top1_prec/y.mean():.2f}x")
    print(f"  Top 5%:  Recall={top5_rec*100:.1f}%, Precision={top5_prec*100:.2f}%, Lift={top5_prec/y.mean():.2f}x")
    print(f"Predictor 2 (CHEATING Future Oracle p* at T_{{m+1}} - includes future weather & condition!):")
    print(f"  PR-AUC:  {prauc2:.5f} | ROC-AUC: {rocauc2:.5f}")
